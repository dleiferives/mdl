    #[test]
    fn score_feedback_parser_is_holder_and_objective_specific() {
        let line = "[Server thread/INFO]: #result has -2147483648 [mdl.case]";
        assert_eq!(
            parse_score_feedback(line, "#result", "mdl.case"),
            Some(i32::MIN)
        );
        assert_eq!(parse_score_feedback(line, "#other", "mdl.case"), None);
        assert_eq!(parse_score_feedback(line, "#result", "wrong"), None);
    }

    #[test]
    fn nbt_feedback_parser_preserves_exact_types_and_rejects_wrong_transport() {
        let line = "[Server thread/INFO]: mdl:test has the following contents: {x:1b,y:[2,3]}";
        assert_eq!(
            parse_nbt_feedback(line).unwrap().to_string(),
            r#"{"x":1b,"y":[2,3]}"#
        );
        assert!(parse_nbt_feedback("not NBT feedback").is_err());
    }


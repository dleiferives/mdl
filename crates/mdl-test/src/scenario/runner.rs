    #[test]
    fn semantic_and_exact_limit_runners_are_structurally_disjoint() {
        let objective = TestName::new("mdl.limit").unwrap();
        let completion = ObservationPath::Score {
            holder: "#completed".into(),
            objective: objective.clone(),
        };
        let exact = ScenarioSpec::new(
            ScenarioId::new("runner/exact").unwrap(),
            GenerationNonce::new(11).unwrap(),
            ScenarioEntry::Export(TestName::new("choose").unwrap()),
        )
        .with_policies(vec![policy()])
        .with_mode(ScenarioMode::ExactLimit(ExactLimitContract::new(
            ExactLimitKind::Sequence,
            10,
            completion,
            false,
        )))
        .with_owned_resources(vec![OwnedResource::Objective(objective)])
        .build()
        .unwrap();

        assert!(validate_runner_surface(&exact, &[deployment()]).is_err());
        assert!(validate_exact_limit_surface(&exact, &[deployment()]).is_ok());
        assert!(validate_exact_limit_surface(&scenario(), &[deployment()]).is_err());
    }

    #[test]
    fn driver_is_fully_materialized_before_server_startup() {
        let scenario = scenario();
        let deployment = deployment();
        let sandbox = ServerSandbox::create(false).unwrap();
        install_driver(&sandbox, &scenario, &[deployment]).unwrap();
        let function = sandbox.root().join(
            "world/datapacks/mdl_ps1_0000000000000009_pack/data/mdl_ps1_0000000000000009/function/policy_0.mcfunction",
        );
        let contents = fs::read_to_string(function).unwrap();
        assert!(!contents.contains("scoreboard players set #arg mdl.reg 1"));
        assert!(contents.contains("function mdl_policy:entry"));
        assert!(contents.contains("scoreboard players set #result mdl.case 1"));
        assert!(contents.contains("scoreboard players set #continued_0 mdl.ps1 1"));
        assert!(
            contents.find("function mdl_policy:entry").unwrap()
                < contents
                    .find("scoreboard players set #continued_0")
                    .unwrap()
        );
        assert!(
            contents
                .find("scoreboard players set #continued_0")
                .unwrap()
                < contents
                    .find("scoreboard players set #result mdl.case 1")
                    .unwrap()
        );
        assert!(!contents.contains("say MDL_PS1_DONE"));
    }

    #[test]
    fn outcome_driver_uses_optional_nbt_channels_without_integer_sentinels() {
        let scenario = ScenarioSpec::new(
            ScenarioId::new("runner/outcome").unwrap(),
            GenerationNonce::new(10).unwrap(),
            ScenarioEntry::Export(TestName::new("choose").unwrap()),
        )
        .with_policies(vec![policy()])
        .with_mode(ScenarioMode::Semantic {
            outcome: Some(CommandOutcomeExpectation::new(
                OutcomeChannelExpectation::Value(true),
                OutcomeChannelExpectation::Value(i32::MIN),
                CompletionExpectation::Continued,
            )),
        })
        .build()
        .unwrap();
        let sandbox = ServerSandbox::create(false).unwrap();
        install_driver(&sandbox, &scenario, &[deployment()]).unwrap();
        let function = sandbox.root().join(
            "world/datapacks/mdl_ps1_000000000000000a_pack/data/mdl_ps1_000000000000000a/function/policy_0.mcfunction",
        );
        let contents = fs::read_to_string(function).unwrap();
        assert!(contents.contains("store success storage"));
        assert!(contents.contains("p0.success byte 1 store result storage"));
        assert!(contents.contains("p0.result int 1 run function mdl_policy:entry"));
        assert!(!contents.contains(&i32::MIN.to_string()));
    }

    #[test]
    fn outcome_expectations_keep_availability_value_and_continuation_separate() {
        let actual = CommandOutcomeObservation {
            success: Some(true),
            result: Some(0),
            continued: true,
        };
        assert!(outcome_matches(
            CommandOutcomeExpectation::new(
                OutcomeChannelExpectation::Value(true),
                OutcomeChannelExpectation::Value(0),
                CompletionExpectation::Continued,
            ),
            actual,
        ));
        assert!(!outcome_matches(
            CommandOutcomeExpectation::new(
                OutcomeChannelExpectation::Unavailable,
                OutcomeChannelExpectation::Value(0),
                CompletionExpectation::Continued,
            ),
            actual,
        ));
        assert!(!outcome_matches(
            CommandOutcomeExpectation::new(
                OutcomeChannelExpectation::Value(true),
                OutcomeChannelExpectation::Value(0),
                CompletionExpectation::Interrupted,
            ),
            actual,
        ));
    }
